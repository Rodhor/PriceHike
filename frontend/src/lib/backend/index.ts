export function isRoundingAction(t: ActionType): boolean {
	return t === 'roundUp' || t === 'roundDown';
}

export function newRule(): Rule {
	return {
		id: crypto.randomUUID(),
		filter: { applyToAll: true, wildcard: '' },
		columns: [],
		action: { type: 'addPercent', value: '5' },
		decimalSettings: { mode: 'keep', places: 2 }
	};
}

function emptyFilter(): RuleFilter {
	return { applyToAll: true, wildcard: '' };
}

// Backend requires `applyToAll: true` when no other filter is set. HANDOFF treats
// an empty wildcard with no threshold as "match all". We honor HANDOFF in the UI
// and convert to the backend's shape here so the user never has to think about it.
function normalizeFilter(filter: RuleFilter): RuleFilter {
	const hasWildcard = !!filter.wildcard && filter.wildcard.length > 0;
	const hasLess = filter.lessThan != null;
	const hasGreater = filter.greaterThan != null;
	if (!hasWildcard && !hasLess && !hasGreater) return emptyFilter();
	return {
		applyToAll: false,
		wildcard: hasWildcard ? filter.wildcard : '',
		lessThan: filter.lessThan,
		greaterThan: filter.greaterThan
	};
}

function normalizeRule(r: Rule): Rule {
	return { ...r, filter: normalizeFilter(r.filter) };
}

// The bindings file declares its returns as `domain.Dataset` etc. — those are
// classes generated by Wails, but the runtime values are plain JSON objects
// with the same fields. Cast through `unknown` because the class type carries
// helper methods we don't have.
function cast<T>(v: unknown): T {
	return v as T;
}

export const backend = {
	// ---- file dialogs ----
	selectImportFile(): Promise<string> {
		return Bindings.SelectImportFile();
	},
	selectExportPath(defaultName: string, kind: ExportKind): Promise<string> {
		return Bindings.SelectExportPath(defaultName, kind);
	},

	// ---- dataset ----
	async loadFile(path: string): Promise<Dataset> {
		return cast<Dataset>(await Bindings.LoadFile(path));
	},

	// ---- preview ----
	async generatePreview(rules: Rule[], sampleSize: number): Promise<PreviewResult> {
		const normalized = rules.map(normalizeRule);
		const raw = await Bindings.GeneratePreview(
			normalized as unknown as Parameters<typeof Bindings.GeneratePreview>[0],
			sampleSize
		);
		return cast<PreviewResult>(raw);
	},

	// ---- export ----
	async applyAndExportCSV(rules: Rule[], destPath: string): Promise<ExportReport> {
		const normalized = rules.map(normalizeRule);
		const raw = await Bindings.ApplyAndExportCSV(
			normalized as unknown as Parameters<typeof Bindings.ApplyAndExportCSV>[0],
			destPath
		);
		return cast<ExportReport>(raw);
	},
	async applyAndExportXLSX(rules: Rule[], destPath: string): Promise<ExportReport> {
		const normalized = rules.map(normalizeRule);
		const raw = await Bindings.ApplyAndExportXLSX(
			normalized as unknown as Parameters<typeof Bindings.ApplyAndExportXLSX>[0],
			destPath
		);
		return cast<ExportReport>(raw);
	},

	// ---- rules I/O ----
	async exportRules(rules: Rule[], destPath: string): Promise<void> {
		return Bindings.ExportRules(
			rules as unknown as Parameters<typeof Bindings.ExportRules>[0],
			destPath
		);
	},
	async importRules(path: string): Promise<Rule[]> {
		const raw = await Bindings.ImportRules(path);
		return cast<Rule[]>(raw);
	},

	// ---- settings ----
	async getSettings(): Promise<Settings> {
		return cast<Settings>(await Bindings.GetSettings());
	},
	setSettings(s: Settings): Promise<void> {
		return Bindings.SetSettings(s as unknown as Parameters<typeof Bindings.SetSettings>[0]);
	},
	async getCSVDelimiters(): Promise<CSVDelimiter[]> {
		// Backend returns `map[string]rune` which marshals to
		// `Record<string, number>` (codepoint integers, not strings). Convert
		// each codepoint to its actual character here so the rest of the
		// frontend works with `{name, value}` pairs and never has to know.
		const raw = await Bindings.GetCSVDelimiters();
		const map = raw as unknown as Record<string, number>;
		return Object.entries(map).map(([name, codepoint]) => ({
			name,
			value: String.fromCodePoint(codepoint)
		}));
	}
};

export function onFileDropped(cb: (filename: string, dataset: Dataset) => void): () => void {
	return EventsOn('file:dropped', (...args: unknown[]) => {
		const filename = args[0] as string;
		const dataset = args[1] as Dataset;
		cb(filename, dataset);
	});
}

export function onFileError(cb: (message: string) => void): () => void {
	return EventsOn('file:error', (...args: unknown[]) => {
		cb(args[0] as string);
	});
}

// Parse the "rule #N: <detail>" prefix the backend uses for per-rule failures
// in both ApplyRules (engine) and ImportRules (boundary). Returns null when
// the message doesn't carry the prefix.
const RULE_INDEX_RE = /^rule #(\d+):\s*(.*)$/;
export function parseRuleError(message: string): { index: number; detail: string } | null {
	const m = RULE_INDEX_RE.exec(message);
	if (!m) return null;
	const idx = parseInt(m[1], 10);
	if (!Number.isFinite(idx) || idx < 1) return null;
	return { index: idx, detail: m[2] };
}
